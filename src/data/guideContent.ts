- 状态记忆：收起或展开的状态会自动记住，下次打开应用保持上次的偏好
- 选中模块记忆：当前选中的模块会被记住，应用启动或刷新后会自动恢复上次浏览的页面，导航栏同时高亮该模块
- 收起后仍可点击图标切换模块，导航能力不丢失

